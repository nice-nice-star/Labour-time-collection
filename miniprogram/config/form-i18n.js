function translateError(message, language, fallback) {
  if (language !== 'en') return message || fallback
  if (errors[message]) return errors[message]
  const match = /^请完整填写项目(\d+)，实际完成时间须为非负数$/.exec(message || '')
  if (match) return `Complete all fields for project ${match[1]} and enter non-negative hours.`
  return fallback
}

